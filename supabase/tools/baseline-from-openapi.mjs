// Generates supabase/migrations/00000000000000_baseline.sql from a project's
// table definitions (the PostgREST OpenAPI description: metadata, no rows).
//
//   node supabase/tools/baseline-from-openapi.mjs <openapi.json> > supabase/migrations/00000000000000_baseline.sql
//
// Carries over: tables, column types, defaults, NOT NULL, primary keys,
// foreign keys and enum types. Not visible in that description, so added here
// by hand: the unique constraints the API's upserts rely on, indexes, and
// ON DELETE behaviour (from supabase-schema.sql). Tables created by later
// migrations (company_profiles) are skipped.
import fs from 'node:fs';

const spec = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
const SKIP = new Set(['company_profiles']);

// Needed by .upsert({ onConflict }) in apps/api/server.ts, or unique in supabase-schema.sql
const UNIQUES = {
  gmail_sessions: [['session_id']],
  email_analysis: [['email_id', 'user_id']],
  country_integrations: [['session_id', 'country_code', 'integration_key']],
  profiles: [['email']],
  subscriptions: [['user_email']],
  customer_portals: [['token']],
  user_preferences: [['user_id']],
  users: [['email']],
};
const ON_DELETE_CASCADE = new Set([
  'user_preferences.user_id', 'email_analysis.user_id', 'shipments.user_id', 'shipments.update_target_id',
  'customer_portals.shipment_id', 'shipment_events.shipment_id', 'gmail_sessions.user_id', 'email_activity.user_id',
  'analytics_daily.user_id', 'document_analysis.user_id', 'tenant_integrations.tenant_id',
]);
const ON_DELETE_SET_NULL = new Set(['profiles.team_id', 'teams.manager_id']);
const INDEXES = [
  'email_analysis(user_id)', 'email_analysis(email_id)', 'email_activity(user_id)', 'email_activity(email_id)',
  'analysis_queue(user_email)', 'analysis_queue(email_id)', 'gmail_sessions(user_id)', 'shipments(user_id)', 'shipments(reference)',
  'shipments(container)', 'shipments(t49_tracking_request_id)', 'shipments(t49_shipment_id)', 'shipment_events(shipment_id)',
  'quotes(session_id)', 'quotes(status)', 'customer_portals(shipment_id)', 'customer_portals(session_id)', 'rate_cards(session_id)',
  'rate_cards(mode)', 'country_integrations(country_code)', 'subscriptions(session_id)', 'subscriptions(stripe_customer_id)',
  'subscriptions(stripe_subscription_id)', 'profiles(team_id)', 'document_analysis(user_id)', 'analytics_daily(user_id)',
];

const q = (id) => `"${id}"`;
const enums = new Map();
const fks = [];
const out = [];

const typeOf = (p) => {
  if (p.format?.startsWith('public.')) {
    const name = p.format.slice('public.'.length);
    enums.set(name, p.enum);
    return name;
  }
  if (p.format) return p.format;
  if (p.type === undefined) return 'jsonb';
  throw new Error(`unknown type ${JSON.stringify(p)}`);
};

const defaultOf = (p, type) => {
  const d = p.default;
  if (d === undefined) return '';
  if (typeof d === 'boolean' || typeof d === 'number') return ` DEFAULT ${d}`;
  if (/^[a-z0-9_.]+\(\)$/i.test(d)) return ` DEFAULT ${d}`; // now(), gen_random_uuid(), extensions.uuid_generate_v4()
  const literal = `'${String(d).replace(/'/g, "''")}'`;
  return ` DEFAULT ${enums.has(type) ? `${literal}::${type}` : literal}`;
};

for (const [table, def] of Object.entries(spec.definitions)) {
  if (SKIP.has(table)) continue;
  const required = new Set(def.required || []);
  const cols = [];
  const pk = [];
  for (const [col, p] of Object.entries(def.properties)) {
    const type = typeOf(p);
    cols.push(`  ${q(col)} ${type}${defaultOf(p, type)}${required.has(col) ? ' NOT NULL' : ''}`);
    if (/<pk\/>/.test(p.description || '')) pk.push(col);
    const fk = (p.description || '').match(/<fk table='([^']+)' column='([^']+)'\/>/);
    if (fk) fks.push({ table, col, refTable: fk[1], refCol: fk[2] });
  }
  if (pk.length) cols.push(`  PRIMARY KEY (${pk.map(q).join(', ')})`);
  for (const u of UNIQUES[table] || []) cols.push(`  UNIQUE (${u.map(q).join(', ')})`);
  out.push(`CREATE TABLE IF NOT EXISTS public.${q(table)} (\n${cols.join(',\n')}\n);`);
}

const header = `-- Freightwizard baseline schema: every table as it exists in production
-- (generated by supabase/tools/baseline-from-openapi.mjs from production's
-- table definitions on ${new Date().toISOString().slice(0, 10)}; no data). Run first on a new project,
-- then the dated migrations in order, then supabase/seed.sql for development.
CREATE EXTENSION IF NOT EXISTS "uuid-ossp" WITH SCHEMA extensions;
CREATE EXTENSION IF NOT EXISTS pgcrypto WITH SCHEMA extensions;
`;
const enumSql = [...enums].map(([name, values]) =>
  `DO $$ BEGIN CREATE TYPE public.${q(name)} AS ENUM (${values.map(v => `'${v}'`).join(', ')}); EXCEPTION WHEN duplicate_object THEN NULL; END $$;`);
const fkSql = fks.map(({ table, col, refTable, refCol }) => {
  const key = `${table}.${col}`;
  const action = ON_DELETE_CASCADE.has(key) ? ' ON DELETE CASCADE' : ON_DELETE_SET_NULL.has(key) ? ' ON DELETE SET NULL' : '';
  const name = `${table}_${col}_fkey`;
  return `DO $$ BEGIN ALTER TABLE public.${q(table)} ADD CONSTRAINT ${q(name)} FOREIGN KEY (${q(col)}) REFERENCES public.${q(refTable)} (${q(refCol)})${action}; EXCEPTION WHEN duplicate_object THEN NULL; END $$;`;
});
const indexSql = INDEXES.map(i => {
  const [, t, c] = i.match(/^([a-z_]+)\(([a-z0-9_]+)\)$/);
  return `CREATE INDEX IF NOT EXISTS ${q(`idx_${t}_${c}`)} ON public.${q(t)} (${q(c)});`;
});
// Only the API (service role) reads and writes; nothing is open to the public key.
const rlsSql = Object.keys(spec.definitions).filter(t => !SKIP.has(t)).map(t => `ALTER TABLE public.${q(t)} ENABLE ROW LEVEL SECURITY;`);

console.log([
  header,
  '-- Enum types', ...enumSql, '',
  '-- Tables', ...out, '',
  '-- Foreign keys (added after all tables: profiles and teams reference each other)', ...fkSql, '',
  '-- Indexes', ...indexSql, '',
  '-- Row level security on, no policies: the public (anon) key sees nothing; the API uses the service role.', ...rlsSql,
].join('\n'));
